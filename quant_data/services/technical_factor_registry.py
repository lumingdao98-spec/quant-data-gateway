class TechnicalFactorRegistryService:
    def __init__(self) -> None:
        self.specs = _specs()

    def list(self) -> list[dict]:
        return [asdict(s) for s in self.specs]

    def by_category(self) -> dict[str, list[dict]]:
        out: dict[str, list[dict]] = {}
        for s in self.specs:
            out.setdefault(s.category, []).append(asdict(s))
        return out

    def by_dimension(self) -> dict[str, list[dict]]:
        out: dict[str, list[dict]] = {}
        for s in self.specs:
            out.setdefault(s.dimension, []).append(asdict(s))
        return out

    def coverage(self) -> dict:
        computed = [s for s in self.specs if "真实源" not in s.score_role]
        return {"total": len(self.specs), "computed_or_derived": len(computed), "not_faked": [s.key for s in self.specs if "真实源" in s.score_role or "公开源缺失" in s.risk_rule]}
